"""v1.8: machine-readable registry of every candidate model, its hyper-parameter search and training settings.

Generated by introspecting the estimator objects that run_fits.py actually fits (src/nested_selection/cands.py), so the
registry cannot drift from the code.  The knock CNN and the fusion / stacking layer are read from their scripts' constants.
usage (repo root):  DURIAN_INTERMEDIATE=intermediate_common EMB_MOBILENET=intermediate_common/rgb/emb_mobilenetv2.npy \
                    python src/audit/model_registry.py
writes: audit/model_registry.csv          one row per base candidate (21 + knock CNN = 22 rows; 26 in C26 are configurations)
        audit/configuration_space.csv     the C26 / C37 configuration candidates of the selection procedures
"""
import os, sys, json, itertools
import numpy as np, pandas as pd
REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
sys.path.insert(0, os.path.join(REPO, "src", "nested_selection"))
os.environ.setdefault("DURIAN_INTERMEDIATE", os.path.join(REPO, "intermediate_common"))
import cands
AOUT = os.environ.get("DURIAN_AUDIT_OUT", os.path.join(REPO, "audit")); os.makedirs(AOUT, exist_ok=True)
from sklearn.model_selection import GridSearchCV
from sklearn.pipeline import Pipeline

def _clean(v):
    if isinstance(v, (np.integer,)): return int(v)
    if isinstance(v, (np.floating,)): return float(v)
    if v is None or isinstance(v, (int, float, str, bool)): return v
    return str(v)

rows = []
dims = {}
for mod in cands.MODS if hasattr(cands, "MODS") else ["thermal", "multispectral", "sound", "rgb"]:
    meta, X = cands.load(mod)
    dims[mod] = ({k: int(v.shape[1]) for k, v in X.items()}, len(meta))
for mod, cl in cands.CANDIDATES.items():
    for c in cl:
        if c == "cnn":
            continue
        xs, est = cands._FACT[mod](c)
        search = isinstance(est, GridSearchCV)
        base = est.estimator if search else est
        steps = [n for n, _ in base.steps] if isinstance(base, Pipeline) else []
        final = base.steps[-1][1] if isinstance(base, Pipeline) else base
        pre = [type(s).__name__ for _, s in base.steps[:-1]] if isinstance(base, Pipeline) else []
        params = {k: _clean(v) for k, v in final.get_params(deep=False).items()}
        grid = {k.split("__")[-1]: [_clean(x) for x in v] for k, v in est.param_grid.items()} if search else {}
        n_grid = int(np.prod([len(v) for v in grid.values()])) if grid else 1
        rows.append(dict(sensor=mod, candidate=c, selected_in_v13=(cands.SELECTED_V13[mod] == c), unit="capture" if mod != "sound" else "recording",
                         feature_set=xs, n_features=dims[mod][0][xs], n_training_units_total=dims[mod][1],
                         preprocessing=" > ".join(pre) or "none", estimator=type(final).__name__,
                         fixed_hyperparameters=json.dumps({k: v for k, v in params.items() if f"{k}" not in grid}, sort_keys=True),
                         searched_hyperparameters=json.dumps(grid), n_grid_points=n_grid,
                         inner_search=(f"GridSearchCV, GroupKFold(n_splits={est.cv.n_splits}) by fruit within the training folds, scoring={est.scoring}, refit on all training folds" if search else "none (fixed settings)"),
                         seed=params.get("random_state", ""), aggregation="mean of capture/recording probabilities per session",
                         fits_per_partition="5 outer + 10 fold-pair", code="src/nested_selection/cands.py; src/nested_selection/run_fits.py"))
cnn_src = open(os.path.join(REPO, "src/nested_selection/cnn_part.py")).read()
assert "EPOCHS = 20" in cnn_src and "lr=2e-3, weight_decay=1e-3" in cnn_src and "max_lr=3e-3" in cnn_src and "label_smoothing=0.05" in cnn_src
rows.append(dict(sensor="sound", candidate="cnn", selected_in_v13=True, unit="knock (log-mel 64 x 31)", feature_set="log-mel spectrogram per knock",
                 n_features=64 * 31, n_training_units_total=15709, preprocessing="standardise with training-fold mean / SD (scalar)",
                 estimator="2-D CNN: 4 blocks [Conv3x3-BN-ReLU-Conv3x3-BN-ReLU-MaxPool2], channels 16/32/64/96, global mean pool, dropout 0.3, linear 3",
                 fixed_hyperparameters=json.dumps({"epochs": 20, "batch_size": 128, "optimizer": "AdamW", "lr": 2e-3, "weight_decay": 1e-3,
                                                   "schedule": "OneCycleLR max_lr 3e-3", "loss": "class-weighted cross-entropy, label_smoothing 0.05",
                                                   "augmentation": "time roll +-3 frames, one frequency mask width 0-8 bins",
                                                   "train_set": "knocks of verified recordings in training folds (106 wrong-session recordings never trained on)",
                                                   "device": "CPU (primary partition, 3 threads) / CUDA GPU (partitions p0-p9)"}),
                 searched_hyperparameters="{}", n_grid_points=1, inner_search="none (fixed settings, no early stopping)", seed=42,
                 aggregation="mean of knock probabilities per recording, then mean over recordings per session",
                 fits_per_partition="5 outer + 10 fold-pair",
                 code="src/common_label/cnn_common.py (primary partition, CPU); src/nested_selection/cnn_part.py (p0-p9, GPU)"))
reg = pd.DataFrame(rows)
reg.to_csv(os.path.join(AOUT, "model_registry.csv"), index=False)

MODS = ["thermal", "multispectral", "sound", "rgb"]
cfg = [dict(space="C26", configuration=m, sensors=m, rule="single sensor (selected family)") for m in MODS]
SUBS = [s for k in range(2, 5) for s in itertools.combinations(MODS, k)]
cfg += [dict(space="C26", configuration="+".join(s) + "|" + r, sensors="+".join(s), rule=r + " of session probabilities") for s in SUBS for r in ("mean", "product")]
cfg += [dict(space="C37 only", configuration="+".join(s) + "|stacking", sensors="+".join(s),
             rule="nested stacking: multinomial logistic regression (class_weight balanced) on inner out-of-fold session probabilities, "
                  "C in {0.03, 0.1, 0.3, 1, 3, 10} by GroupKFold over fruits, macro-F1") for s in SUBS]
cs = pd.DataFrame(cfg)
cs.to_csv(os.path.join(AOUT, "configuration_space.csv"), index=False)
print(reg[["sensor", "candidate", "feature_set", "n_features", "estimator", "n_grid_points"]].to_string())
print("configurations:", cs.space.value_counts().to_dict())
