"""v1.8: assemble Supplementary Tables S1-S20 (v1.9: S1-S22) from the repository's result and data files.

usage (repo root):  python src/audit/build_supplementary_tables.py [OUTDIR]      (default audit/supplementary)
Every table is derived from a file regenerated by run_all.sh (results/, results/v14, v15, v17, v19) or shipped as data (data/);
Table S18 (literature design extraction) is curated input and is copied from data/literature/.
"""
import os, sys, shutil
import numpy as np, pandas as pd
REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
os.chdir(REPO)
OUT = sys.argv[1] if len(sys.argv) > 1 else "audit/supplementary"; os.makedirs(OUT, exist_ok=True)
RES = os.environ.get("DURIAN_RESULTS", "results")
r = lambda f: pd.read_csv(os.path.join(RES, f), low_memory=False)
T = {}
fu = r("fusion_results.csv")
T["S1_fusion_ablation_all_subsets"] = fu[fu.record == "summary"].drop(columns=["accuracy", "macro_f1", "n", "fold", "record"], errors="ignore")
T["S2_per_fold_scores"] = r("fusion_results_per_fold.csv")
T["S3_leave_one_batch_out"] = r("lobo_table.csv")
lab = pd.read_csv("data/session_labels_common.csv")
st = r("session_table.csv").set_index("session_id")
s4 = lab[~lab.unanimous].copy(); s4["in_evaluation_268"] = s4.session_id.map(st.in_main_analysis.astype(str) == "True")
T["S4_label_disagreement_sessions"] = s4
T["S5_error_analysis"] = r("error_analysis.csv")
T["S6_nested_vs_global_stacking"] = r("nested_vs_global_stacking.csv")
T["S7_sound_recording_manifest"] = pd.read_csv("data/sound_recording_manifest.csv")
T["S8_sound_session_evidence"] = pd.read_csv("data/sound_session_evidence.csv")
T["S9_sound_matching_sensitivity"] = r("sound_matching_sensitivity.csv")
T["S10_session_labels_common"] = lab
T["S11_label_policy_sensitivity"] = r("label_policy_sensitivity.csv")
T["S12_nested_selection_choices"] = r("v14/nested_choices.csv")
T["S13_partition_sensitivity"] = r("v14/partition_sensitivity.csv")
# v1.9.1: H1-H3 are retrospectively designated primary comparisons (not confirmatory); the "primary" differences of v1.4 are
# fold-mean differences on the primary partition, so the columns are renamed to say so (values unchanged)
S14 = r("v14/comparisons_v14.csv"); S14["role"] = S14.role.replace({"confirmatory": "primary_retrospective"})
T["S14_dependence_aware_comparisons"] = S14.rename(columns={"d_acc_pp_primary": "d_acc_pp_primary_foldmean", "d_f1_pp_primary": "d_f1_pp_primary_foldmean"})
# S15 thermal quantization ablation
lab15 = {"orig_all": "Original quantization, all 67 features", "orig_rel": "Original quantization, fruit-relative 52 features",
         "harm_all": "Harmonized 0.5 °C, all 67 features", "harm_rel": "Harmonized 0.5 °C, fruit-relative 52 features",
         "harm_quant_only": "Harmonized distinct-value count only", "orig_quant_only": "Original distinct-value count only"}
s15 = r("v15/thermal_ablation.csv"); s15.insert(0, "feature_set", s15.features.map(lab15)); s15 = s15.drop(columns="features")
s15["n_sessions"] = 268; s15["majority_rate_all"] = 0.593; s15["majority_rate_LOBO_Imm_Mat_Over"] = "0.634/0.568/0.575"
T["S15_thermal_quantization_ablation"] = s15
T["S16_rgb_masking_cross_camera"] = pd.concat([r("v15/rgb_masking.csv").assign(block="fruit_grouped_cv_268_sessions_foldmean"),
                                               r("v15/rgb_cross_camera.csv").assign(block="cross_camera_fruit_disjoint_primary_partition_pooled"),
                                               r("v15/rgb_paired_tests.csv").assign(block="fruit_clustered_mcnemar_primary_partition")], ignore_index=True)
T["S17_device_identical_sessions"] = pd.concat([r("v15/device_identical_sessions.csv").assign(block="results_163_identical_sessions", majority_rate=0.589),
                                                r("v15/device_paired_tests.csv").assign(block="paired_test_A_vs_B")], ignore_index=True)
for k in ["S16_rgb_masking_cross_camera", "S17_device_identical_sessions"]:
    T[k] = T[k][["block"] + [c for c in T[k].columns if c != "block"]]
T["S18_literature_design_extraction"] = pd.read_csv("data/literature/TableS18_literature_design_extraction.csv")
# S19 multispectral wavelength ablation
D = r("v15/ms_wavelength_ablation_detail.csv"); D["kind"] = np.where(D.variant.str.startswith("perm"), "perm", D.variant)
lab19 = {"assumed": "Published features, assumed mapping (720–980 nm ascending)", "no_wavelength": "Without slope/curvature features (3 removed)",
         "alt_centres": "Slope/curvature with alternative centres 720,760,795,830,870,905,940,980 nm",
         "perm": "20 random tile orders (all order-dependent features recomputed)", "plsda_raw8": "PLS-DA on 8 raw band means (order-free)"}
rows = []
for k in ["assumed", "no_wavelength", "alt_centres", "plsda_raw8", "perm"]:
    a = D[(D.kind == k) & (D.partition == "p0")]; b = D[D.kind == k]
    q = dict(variant=lab19[k],
             primary_acc=round(a.acc.mean(), 3) if k != "perm" else f"{a.acc.min():.3f}–{a.acc.max():.3f} (mean {a.acc.mean():.3f})",
             primary_f1=round(a.f1.mean(), 3) if k != "perm" else f"{a.f1.min():.3f}–{a.f1.max():.3f} (mean {a.f1.mean():.3f})")
    q.update(dict(ten_partitions_acc_mean=round(b.acc.mean(), 3), ten_min=round(b.acc.min(), 3), ten_max=round(b.acc.max(), 3),
                  ten_f1_mean=round(b.f1.mean(), 3)) if k != "perm" else
             dict(ten_partitions_acc_mean="primary partition only", ten_min="", ten_max="", ten_f1_mean=""))
    rows.append(q)
s19 = pd.DataFrame(rows); s19["model"] = ["LR (selected)"] * 3 + ["PLS-DA"] + ["LR (selected)"]
T["S19_multispectral_wavelength_ablation"] = s19
# S20 development pipelines vs selection procedures
S = r("v17/matched_space_summary.csv"); C = r("v17/procedure_level_comparisons.csv")
S.columns = ["estimate", "primary_acc", "primary_f1", "ten_partitions_acc_mean", "ten_min", "ten_max"]
desc = {"posthoc_C26": "Post hoc best of 26 configurations on the primary partition (sound+rgb|mean), held fixed",
        "posthoc_C37": "Post hoc best of 37 configurations incl. stacking (sound+rgb|stacking), held fixed",
        "nested_cfg_fixedfam": "Configuration selected per outer fold from inner predictions, families fixed",
        "nested_cfg_nestedfam": "Configuration and families selected per outer fold",
        "nested_single_nestedfam": "Best single sensor selected per outer fold (families selected)"}
S.insert(1, "description", S.estimate.map(lambda e: desc.get(e, ("Development pipeline (families fixed): " if e.startswith("fixed_") else
                                                                 "Families selected per outer fold: ") + e.split("_", 1)[1])))
S.insert(0, "block", "estimates"); C.insert(0, "block", "procedure_level_comparisons_exploratory")
T["S20_development_vs_procedure_matched_space"] = pd.concat([S, C], ignore_index=True)
# v1.9 S21 every estimate as fold-mean, pooled and across-partition macro-F1 / accuracy with pooled class recall
E = r("v19/estimates_summary.csv")
E.insert(1, "description", E.estimate.map(lambda e: desc.get(e, ("Development pipeline (families fixed): " if e.startswith("fixed_") else
                                                                  "Families selected per outer fold: ") + e.split("_", 1)[1])))
num = E.select_dtypes("number").columns; E[num] = E[num].round(4)
T["S21_estimates_by_summary_type"] = E
# v1.9 S22 paired comparisons in macro-F1 (primary) and accuracy (secondary)
P = r("v19/comparisons_macro_f1.csv"); num = P.select_dtypes("number").columns; P[num] = P[num].round(4)
T["S22_paired_comparisons_macro_f1"] = P
for k, d in T.items():
    d.to_csv(f"{OUT}/Table{k}.csv", index=False)
print(len(T), "tables ->", OUT)
